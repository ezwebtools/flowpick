function detectSystemLocale(): string {
  const uiLang = browser.i18n.getUILanguage()
  if (BROWSER_LANG_MAP[uiLang]) return BROWSER_LANG_MAP[uiLang]
  const base = uiLang.split('-')[0]
  if (BROWSER_LANG_MAP[base]) return BROWSER_LANG_MAP[base]
  return 'en'
}

export type ThemeMode = 'system' | 'light' | 'dark'
export type DensityMode = 'compact' | 'comfortable'

const APPEARANCE_KEY = 'ext_appearance'

export const currentLocale = ref<LocaleCode>('system')
export const currentTheme = ref<ThemeMode>('system')
export const currentDensity = ref<DensityMode>('compact')

export async function loadAppearance() {
  const result = await browser.storage.local.get(APPEARANCE_KEY)
  const stored = result[APPEARANCE_KEY] as any
  if (stored) {
    if (stored.locale && LOCALE_OPTIONS.some(o => o.code === stored.locale)) {
      currentLocale.value = stored.locale as LocaleCode
    }
    if (stored.theme && ['system', 'light', 'dark'].includes(stored.theme)) {
      currentTheme.value = stored.theme as ThemeMode
    }
    if (stored.density && ['compact', 'comfortable'].includes(stored.density)) {
      currentDensity.value = stored.density as DensityMode
    }
  }
  applyTheme(currentTheme.value)
}

export async function saveAppearance() {
  await browser.storage.local.set({
    [APPEARANCE_KEY]: {
      locale: currentLocale.value,
      theme: currentTheme.value,
      density: currentDensity.value,
    }
  })
}

export function applyTheme(theme: ThemeMode) {
  const root = document.documentElement
  const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches
  if (theme === 'dark' || (theme === 'system' && prefersDark)) {
    root.classList.add('dark')
  } else {
    root.classList.remove('dark')
  }
}

const resolvedLocale = computed<string>(() => {
  if (currentLocale.value === 'system') return detectSystemLocale()
  return currentLocale.value
})

const activeMessages = computed<Messages>(() => {
  return localizedMessages[resolvedLocale.value] ?? messagesMap[resolvedLocale.value] ?? messagesMap['en']
})

export function t(key: string, substitutions?: string | string[]): string {
  const msg = activeMessages.value[key] ?? messagesMap['en'][key] ?? key
  if (!substitutions) return msg
  const subs = Array.isArray(substitutions) ? substitutions : [substitutions]
  return msg.replace(/\$(\d+)/g, (_, n) => subs[parseInt(n) - 1] ?? '')
}

export function useI18n() {
  return { t, currentLocale, currentTheme, resolvedLocale }
}
